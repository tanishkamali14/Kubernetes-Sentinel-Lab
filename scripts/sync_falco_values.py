#!/usr/bin/env python3
"""Regenerate helm/falco-values.yaml customRules from falco/*.yaml so the two never drift."""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / 'helm' / 'falco-values.yaml'
HEADER = '# Generated by scripts/sync_falco_values.py from falco/*.yaml. Edit those files, then re-run it.\n'
FALCO_SETTINGS = """falco:
  json_output: true
  json_include_output_property: true
  json_include_output_fields_property: true
  time_format_iso_8601: true
  # libs warnings (for example short-lived processes whose fd path cannot be resolved) share the log stream
  # with alerts and can corrupt an alert line; keep errors only. Falco's own startup lines are unaffected.
  libs_logger:
    enabled: true
    severity: error
"""


def render():
    parts = [HEADER, 'customRules:\n']
    for rules in sorted((ROOT / 'falco').glob('*.yaml')):
        parts.append(f'  {rules.name}: |-\n')
        for line in rules.read_text(encoding='utf-8').rstrip('\n').splitlines():
            parts.append(f'    {line}\n' if line.strip() else '\n')
    parts.append(FALCO_SETTINGS)
    return ''.join(parts)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true', help='exit 1 if helm/falco-values.yaml is out of date')
    args = p.parse_args()
    wanted = render()
    current = TARGET.read_text(encoding='utf-8') if TARGET.exists() else ''
    if args.check:
        if current != wanted:
            print('helm/falco-values.yaml is out of date; run scripts/sync_falco_values.py', file=sys.stderr)
            return 1
        return 0
    with TARGET.open('w', encoding='utf-8', newline='\n') as f:
        f.write(wanted)
    print(f'wrote {TARGET.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
